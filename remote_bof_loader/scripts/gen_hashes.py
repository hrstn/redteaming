#!/usr/bin/env python3
"""
gen_hashes.py — generate src/hashes.h for the BOF loader.

All API and DLL names resolved at runtime via PEB walk are hashed here with
FNV1a-32 (case-insensitive) so the loader source stays readable and the hashes
can be audited.
"""

from pathlib import Path


H_MAGIC_KEY = 0x811C9DC5
H_MAGIC_PRIME = 0x01000193


API_NAMES = [
    # DLLs
    "kernel32.dll",
    "ntdll.dll",
    "winhttp.dll",
    # kernel32 APIs used by the loader
    "GetProcessHeap",
    "HeapAlloc",
    "HeapFree",
    "GetSystemInfo",
    "GetTickCount64",
    "GetProcAddress",
    "GetModuleHandleA",
    "CreateFileA",
    "ReadFile",
    "CloseHandle",
    "GetFileSize",
    "GetStdHandle",
    "WriteFile",
    # ntdll APIs
    "LdrLoadDll",
    "NtAllocateVirtualMemory",
    "NtProtectVirtualMemory",
    "NtFreeVirtualMemory",
    "NtCreateThreadEx",
    "NtWaitForSingleObject",
    "NtQuerySystemInformation",
    "NtClose",
    "RtlAddFunctionTable",
    "RtlDeleteFunctionTable",
    # winhttp APIs
    "WinHttpOpen",
    "WinHttpConnect",
    "WinHttpOpenRequest",
    "WinHttpSendRequest",
    "WinHttpReceiveResponse",
    "WinHttpQueryDataAvailable",
    "WinHttpReadData",
    "WinHttpCloseHandle",
    "WinHttpSetOption",
    "WinHttpSetTimeouts",
]


def fnv1a32(s: str) -> int:
    h = H_MAGIC_KEY
    for c in s:
        b = ord(c)
        if 0x61 <= b <= 0x7A:
            b -= 0x20
        h ^= b
        h = (h * H_MAGIC_PRIME) & 0xFFFFFFFF
    return h


def c_name(s: str) -> str:
    # kernel32.dll -> H_KERNEL32_DLL, GetProcessHeap -> H_GETPROCESSHEAP
    key = s.upper().replace(".", "_").replace("-", "_")
    return f"H_{key}"


def main() -> int:
    root = Path(__file__).parent.parent
    out = root / "src" / "hashes.h"
    lines = [
        "/* generated by scripts/gen_hashes.py — do not edit manually */",
        "#pragma once",
        "",
    ]
    for name in API_NAMES:
        lines.append(f"#define {c_name(name):<36} 0x{fnv1a32(name):08X}u  /* {name} */")
    out.write_text("\n".join(lines) + "\n")
    print(f"[+] wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
